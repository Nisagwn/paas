package build

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	javaJDKImage    = "eclipse-temurin:21-jdk"
	javaJREImage    = "eclipse-temurin:21-jre"
	mavenImage      = "maven:3.9-eclipse-temurin-21"
	gradleImage     = "gradle:8-jdk21"
	javaToolOptions = "-XX:MaxRAMPercentage=75.0" // the JVM default is 25% of the memory limit
)

// javaBuildTool returns "maven", "gradle" or "".
func javaBuildTool(dir string) string {
	switch {
	case exists(dir, "pom.xml"):
		return "maven"
	case exists(dir, "build.gradle"), exists(dir, "build.gradle.kts"):
		return "gradle"
	}
	return ""
}

// javaBuild describes one build tool.
type javaBuild struct {
	image    string
	cache    string   // cache mount target
	files    []string // build files copied before the source
	dirs     []string // wrapper directories copied before the source
	wrapper  string   // mvnw or gradlew, if the repo has one
	run      string
	prefetch string // goal that resolves dependencies
	build    string
	out      string // where the jars land
}

func detectJavaBuild(dir, tool string) javaBuild {
	var b javaBuild
	if tool == "maven" {
		b = javaBuild{image: mavenImage, cache: "/root/.m2", run: "mvn -B",
			prefetch: "dependency:go-offline", build: "-DskipTests package", out: "target"}
		b.files = []string{"pom.xml"}
		if exists(dir, "mvnw") {
			b.image, b.wrapper, b.run = javaJDKImage, "mvnw", "./mvnw -B"
			b.files = append(b.files, "mvnw")
			b.dirs = []string{".mvn"}
		}
		return b
	}
	b = javaBuild{image: gradleImage, cache: "/root/.gradle", run: "gradle --no-daemon",
		prefetch: "dependencies", build: "assemble", out: "build/libs"}
	for _, f := range []string{"build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts", "gradle.properties"} {
		if exists(dir, f) {
			b.files = append(b.files, f)
		}
	}
	if exists(dir, "gradlew") {
		b.image, b.wrapper, b.run = javaJDKImage, "gradlew", "./gradlew --no-daemon"
		b.files = append(b.files, "gradlew")
		b.dirs = []string{"gradle"}
	}
	return b
}

// detectJava builds with Maven or Gradle (the repo's wrapper if it has one)
// and runs the largest jar the build produced, which is the fat jar for Spring
// Boot, shade and shadow builds, with java -jar on a JRE.
func detectJava(dir string, o Options) (Plan, error) {
	tool := javaBuildTool(dir)
	b := detectJavaBuild(dir, tool)
	mount := "--mount=type=cache,target=" + b.cache
	// Wrappers committed from Windows may lack the executable bit or use CRLF.
	fixWrapper := ""
	if b.wrapper != "" {
		fixWrapper = fmt.Sprintf("RUN sed -i 's/\\r$//' %[1]s && chmod +x %[1]s\n", b.wrapper)
	}

	var df strings.Builder
	fmt.Fprintf(&df, "# generated by paas: java 21 (%s)\n", tool)
	fmt.Fprintf(&df, "FROM %s AS build\n", b.image)
	if tool == "gradle" {
		df.WriteString("ENV GRADLE_USER_HOME=/root/.gradle\n")
	}
	df.WriteString("WORKDIR /src\n")
	// Build files first, so dependency resolution is cached until they change.
	for _, d := range b.dirs {
		if exists(dir, d) {
			fmt.Fprintf(&df, "COPY %s %s/\n", d, d)
		}
	}
	fmt.Fprintf(&df, "COPY %s ./\n", strings.Join(b.files, " "))
	df.WriteString(fixWrapper)
	how := ""
	if o.InstallCommand != "" {
		// A custom install step may need any file of the project.
		df.WriteString("COPY . .\n")
		df.WriteString(fixWrapper)
		fmt.Fprintf(&df, "RUN %s %s\n", mount, o.InstallCommand)
		how = "install command: " + o.InstallCommand + ", "
	} else {
		fmt.Fprintf(&df, "RUN %s %s %s\n", mount, b.run, b.prefetch)
		df.WriteString("COPY . .\n")
		df.WriteString(fixWrapper)
	}
	if o.BuildCommand != "" {
		fmt.Fprintf(&df, "RUN %s %s\n", mount, o.BuildCommand)
		how += "build command: " + o.BuildCommand + ", "
	} else {
		fmt.Fprintf(&df, "RUN %s %s %s\n", mount, b.run, b.build)
	}
	fmt.Fprintf(&df, `RUN jar=$(ls -S %[1]s/*.jar 2>/dev/null | grep -Ev '(-sources|-javadoc|-tests|-plain)\.jar$|/original-[^/]*$' | head -n 1); \
    if [ -z "$jar" ]; then echo "the build produced no runnable jar in %[1]s/" >&2; exit 1; fi; \
    echo "running $jar"; cp "$jar" /app.jar
`, b.out)

	fmt.Fprintf(&df, "FROM %s\nWORKDIR /app\nCOPY --from=build /app.jar /app/app.jar\n", javaJREImage)
	cmd := fmt.Sprintf("CMD [%q, %q, %q]\n", "java", "-jar", "/app/app.jar")
	if start, startHow := startCommand(dir, o); start != "" {
		// Start commands name the jar by its build path.
		fmt.Fprintf(&df, "COPY --from=build /src/%[1]s/ /app/%[1]s/\n", b.out)
		cmd, how = shellCmd(start), how+startHow
	} else {
		how += "java -jar"
	}
	// SERVER_PORT is Spring Boot's port setting.
	fmt.Fprintf(&df, "ENV PORT=%[1]d SERVER_PORT=%[1]d JAVA_TOOL_OPTIONS=%[2]s\nEXPOSE %[1]d\nUSER %[3]s\n",
		Port, javaToolOptions, appUser)
	df.WriteString(cmd)
	name := "Java"
	for _, f := range b.files {
		if body, err := os.ReadFile(filepath.Join(dir, f)); err == nil && strings.Contains(string(body), "spring-boot") {
			name = "Spring Boot"
		}
	}
	return Plan{Kind: KindJava, Framework: name, Summary: fmt.Sprintf("java 21 (%s, %s)", strings.Fields(b.run)[0], how),
		Dockerfile: df.String()}, nil
}
