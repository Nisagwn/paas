func TestDetectWithSettings(t *testing.T) {
	nodeServer := map[string]string{"package.json": pkg(nil, map[string]string{"build": "tsc", "start": "node dist/a.js"}), "package-lock.json": "{}"}
	t.Run("node commands and version", func(t *testing.T) {
		checkPlan(t, nodeServer, Options{InstallCommand: "npm ci --omit=optional", BuildCommand: "npm run build:all",
			StartCommand: "node dist/b.js --port $PORT", NodeVersion: "20"}, "Node.js",
			[]string{"FROM node:20-alpine AS build", "COPY . .\nRUN --mount=type=cache,target=/root/.npm npm ci --omit=optional",
				"RUN npm run build:all", `CMD ["sh", "-c", "node dist/b.js --port $PORT"]`},
			[]string{"COPY package.json package-lock.json ./", "npm start", "node:22"})
	})
	t.Run("node output directory", func(t *testing.T) {
		checkPlan(t, map[string]string{"package.json": pkg(nil, map[string]string{"build": "gen"})}, Options{OutputDirectory: "site/out"}, "Node.js",
			[]string{"RUN npm run build", "COPY --from=build /app/site/out/ /usr/share/nginx/html/"}, []string{"for d in"})
	})
	t.Run("Vite output directory", func(t *testing.T) {
		checkPlan(t, map[string]string{"package.json": pkg([]string{"vite"}, nil)}, Options{OutputDirectory: "public-build"}, "Vite",
			[]string{"RUN node_modules/.bin/vite build", "/app/public-build/"}, nil)
	})
	t.Run("framework override beats a Dockerfile and detection", func(t *testing.T) {
		checkPlan(t, map[string]string{"Dockerfile": "FROM scratch", "package.json": pkg([]string{"react"}, map[string]string{"build": "vite build"})},
			Options{Framework: FrameworkVite}, "Vite", []string{"/app/dist/"}, nil)
	})
	t.Run("Next.js start override runs in the build image", func(t *testing.T) {
		checkPlan(t, map[string]string{"package.json": pkg([]string{"next"}, nil), "next.config.js": "output: 'standalone'"},
			Options{StartCommand: "node custom.js"}, "Next.js", []string{`CMD ["sh", "-c", "node custom.js"]`}, []string{"standalone"})
	})
	t.Run("python", func(t *testing.T) {
		checkPlan(t, map[string]string{"requirements.txt": "django\n", "manage.py": "", "proj/wsgi.py": ""},
			Options{InstallCommand: "pip install -e .", BuildCommand: "python manage.py collectstatic --noinput",
				StartCommand: "gunicorn proj.wsgi -b 0.0.0.0:$PORT"}, "Django",
			[]string{"COPY . .\nRUN python -m venv /opt/venv\nRUN --mount=type=cache,target=/root/.cache/pip pip install -e .",
				"RUN python manage.py collectstatic --noinput\nENV PORT=8080", `CMD ["sh", "-c", "gunicorn proj.wsgi -b 0.0.0.0:$PORT"]`},
			[]string{"pip install -r requirements.txt", "pip install gunicorn"})
	})
	t.Run("ruby", func(t *testing.T) {
		checkPlan(t, map[string]string{"Gemfile": "gem 'puma'\n", "config.ru": ""},
			Options{InstallCommand: "bundle install --deployment", BuildCommand: "bundle exec rake assets", StartCommand: "bundle exec puma -p $PORT"}, "Rack",
			[]string{"bundle install --deployment", "RUN bundle exec rake assets", `CMD ["sh", "-c", "bundle exec puma -p $PORT"]`},
			[]string{"bundle install --jobs 4"})
	})
	t.Run("java", func(t *testing.T) {
		checkPlan(t, map[string]string{"pom.xml": "<artifactId>spring-boot-starter-web</artifactId>"},
			Options{BuildCommand: "mvn -B -Pprod package", StartCommand: "java -jar target/app.jar"}, "Spring Boot",
			[]string{"--mount=type=cache,target=/root/.m2 mvn -B -Pprod package", "COPY --from=build /src/target/ /app/target/",
				`CMD ["sh", "-c", "java -jar target/app.jar"]`},
			[]string{"-DskipTests package"})
	})
	t.Run("go", func(t *testing.T) {
		checkPlan(t, map[string]string{"go.mod": "module x\n\ngo 1.23\n", "main.go": "package main\n"},
			Options{BuildCommand: "go build -o /out/app ./cmd/web", StartCommand: "/app --serve"}, "Go",
			[]string{"go build -o /out/app ./cmd/web", "test -x /out/app", `ENTRYPOINT ["/app","--serve"]`, "USER 65532:65532"},
			[]string{"-trimpath"})
	})
	t.Run("static output directory", func(t *testing.T) {
		checkPlan(t, map[string]string{"site/index.html": ""}, Options{OutputDirectory: "site"}, "Static",
			[]string{"COPY site/ /usr/share/nginx/html/"}, nil)
	})
	t.Run("forced kinds need their files", func(t *testing.T) {
		for _, fw := range []string{KindDockerfile, KindGo, KindPython, KindRuby, KindJava, FrameworkNext} {
			if _, err := DetectWith(writeTree(t, map[string]string{"index.html": ""}), Options{Framework: fw}); err == nil ||
				!strings.Contains(err.Error(), "framework setting") {
				t.Errorf("%s: err = %v", fw, err)
			}
		}
	})
}

func TestNormalizeSettings(t *testing.T) {
	got, err := NormalizeSettings(store.BuildSettings{RootDirectory: " ./apps//web/ ", OutputDirectory: ".",
		Framework: " vite ", BuildCommand: "  npm run build  ", NodeVersion: "v20.11"})
	if err != nil {
		t.Fatal(err)
	}
	if got.RootDirectory != "apps/web" || got.OutputDirectory != "" || got.Framework != "vite" ||
		got.BuildCommand != "npm run build" || got.NodeVersion != "20.11" {
		t.Fatalf("normalized = %+v", got)
	}
	for _, f := range Frameworks {
		if _, err := NormalizeSettings(store.BuildSettings{Framework: f.ID}); err != nil {
			t.Errorf("framework %s: %v", f.ID, err)
		}
	}
	for _, ok := range []string{"22", "20.18.1", "lts"} {
		if _, err := NormalizeSettings(store.BuildSettings{NodeVersion: ok}); err != nil {
			t.Errorf("node %s: %v", ok, err)
		}
	}
	bad := []store.BuildSettings{
		{RootDirectory: "/abs"}, {RootDirectory: ".."}, {RootDirectory: "a/../.."}, {RootDirectory: "a/../b"},
		{RootDirectory: `a\b`}, {RootDirectory: "a b"}, {RootDirectory: strings.Repeat("a", 300)},
		{OutputDirectory: "../dist"}, {OutputDirectory: "/dist"},
		{Framework: "django"}, {Framework: "NEXTJS"},
		{InstallCommand: "a\nRUN b"}, {BuildCommand: "a\rb"}, {StartCommand: `a \`}, {BuildCommand: strings.Repeat("x", 1025)},
		{NodeVersion: "22-alpine"}, {NodeVersion: "latest"}, {NodeVersion: "22; rm"},
	}
	for _, b := range bad {
		if _, err := NormalizeSettings(b); err == nil {
			t.Errorf("%+v: accepted", b)
		}
	}
}

// The root directory is the build context and detection happens inside it.
func TestBuilderRootDirectory(t *testing.T) {
	base, first, _ := gitRepo(t, "o/mono", map[string]string{
		"package.json":          `{"workspaces":["apps/*"]}`,
		"apps/web/package.json": pkg([]string{"vite"}, map[string]string{"build": "vite build"}),
		"apps/api/go.mod":       "module api\n",
	})
	eng := &fakeEngine{}
	b := &Builder{Engine: eng, Registry: "r", GitBaseURL: base, WorkDir: t.TempDir()}
	d := store.Deployment{ID: 3, AppName: "web", Repo: "o/mono", CommitSHA: first, Branch: "main"}
	var logs logSink
	res, err := b.Build(context.Background(), d, store.BuildSettings{RootDirectory: "apps/web", NodeVersion: "20"}, logs.log)
	if err != nil {
		t.Fatalf("%v\n%s", err, logs.text())
	}
	if res.Framework != "Vite" || !strings.Contains(eng.dockerfile, "FROM node:20-alpine") {
		t.Fatalf("framework %q, Dockerfile:\n%s", res.Framework, eng.dockerfile)
	}
	// hello.txt lies in the repository root, outside the context.
	if filepath.Base(eng.spec.ContextDir) != "web" || eng.hello != "" {
		t.Fatalf("context = %s", eng.spec.ContextDir)
	}
	for _, want := range []string{"==> root directory: apps/web", "==> framework: Vite"} {
		if !strings.Contains(logs.text(), want) {
			t.Errorf("log lacks %q:\n%s", want, logs.text())
		}
	}

	for root, msg := range map[string]string{"apps/nope": "not found", "../x": "build settings"} {
		_, err := b.Build(context.Background(), d, store.BuildSettings{RootDirectory: root}, func(string, ...any) {})
		if err == nil || !strings.Contains(err.Error(), msg) {
			t.Errorf("root %q: err = %v, want %q", root, err, msg)
		}
	}
}

func TestRootDirSymlinkEscape(t *testing.T) {
	src := t.TempDir()
	outside := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(src, "link")); err != nil {
		t.Skip("symlinks not available:", err)
	}
	if _, err := rootDir(src, "link"); err == nil || !strings.Contains(err.Error(), "outside") {
		t.Fatalf("err = %v", err)
	}
	os.MkdirAll(filepath.Join(src, "in"), 0o755)
	if dir, err := rootDir(src, "in"); err != nil || filepath.Base(dir) != "in" {
		t.Fatalf("dir = %q, %v", dir, err)
	}
}
