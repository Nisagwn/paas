// pkg returns a package.json with the given dependencies and scripts.
func pkg(deps []string, scripts map[string]string) string {
	var b strings.Builder
	b.WriteString(`{"dependencies":{`)
	for i, d := range deps {
		if i > 0 {
			b.WriteString(",")
		}
		b.WriteString(`"` + d + `":"*"`)
	}
	b.WriteString(`},"scripts":{`)
	i := 0
	for k, v := range scripts {
		if i > 0 {
			b.WriteString(",")
		}
		b.WriteString(`"` + k + `":"` + v + `"`)
		i++
	}
	b.WriteString("}}")
	return b.String()
}

// checkPlan runs DetectWith and checks the generated Dockerfile.
func checkPlan(t *testing.T, files map[string]string, o Options, framework string, want, not []string) Plan {
	t.Helper()
	plan, err := DetectWith(writeTree(t, files), o)
	if err != nil {
		t.Fatal(err)
	}
	if plan.Framework != framework {
		t.Errorf("framework = %q, want %q", plan.Framework, framework)
	}
	if plan.Dockerfile != "" {
		if !strings.HasPrefix(plan.Dockerfile, "# generated by paas: ") || strings.Contains(plan.Dockerfile, "# syntax=") {
			t.Errorf("Dockerfile must start with the paas comment and have no syntax directive:\n%s", plan.Dockerfile)
		}
		// Every image that runs a process of ours drops root numerically;
		// nginx-unprivileged does it in its base image.
		if !strings.Contains(plan.Dockerfile, "USER ") && !strings.Contains(plan.Dockerfile, "FROM "+nginxImage) {
			t.Errorf("no numeric USER:\n%s", plan.Dockerfile)
		}
	}
	for _, w := range want {
		if !strings.Contains(plan.Dockerfile, w) {
			t.Errorf("Dockerfile lacks %q:\n%s", w, plan.Dockerfile)
		}
	}
	for _, n := range not {
		if strings.Contains(plan.Dockerfile, n) {
			t.Errorf("Dockerfile should not contain %q:\n%s", n, plan.Dockerfile)
		}
	}
	return plan
}

