// ---- node ----

const defaultNodeVersion = "22"

// nodeImage is the node image for a node_version setting ("" = default).
func nodeImage(version string) string {
	if version == "" {
		version = defaultNodeVersion
	}
	return "node:" + version + "-alpine"
}

type packageJSON struct {
	Main            string            `json:"main"`
	Scripts         map[string]string `json:"scripts"`
	Dependencies    map[string]string `json:"dependencies"`
	DevDependencies map[string]string `json:"devDependencies"`
}

// packageManager describes how to install dependencies and run scripts.
type packageManager struct {
	name     string
	lockfile string
	setup    string // extra RUN before install, if any
	install  string
	run      string // prefix for running a package.json script
	cache    string // cache mount target
}

// corepack ships with node up to 24; newer images install it first.
const corepackSetup = "(command -v corepack >/dev/null || npm install -g corepack) && corepack enable"

func detectPackageManager(dir string) packageManager {
	switch {
	case exists(dir, "pnpm-lock.yaml"):
		return packageManager{"pnpm", "pnpm-lock.yaml", corepackSetup,
			"pnpm install --frozen-lockfile", "pnpm run", "/root/.local/share/pnpm/store"}
	case exists(dir, "yarn.lock"):
		return packageManager{"yarn", "yarn.lock", "",
			"yarn install --frozen-lockfile", "yarn run", "/usr/local/share/.cache/yarn"}
	case exists(dir, "package-lock.json"):
		return packageManager{"npm", "package-lock.json", "",
			"npm ci", "npm run", "/root/.npm"}
	}
	return packageManager{"npm", "", "", "npm install", "npm run", "/root/.npm"}
}

// nodeApp is a package.json project being planned.
type nodeApp struct {
	dir   string
	pkg   packageJSON
	pm    packageManager
	o     Options
	image string
}

func detectNode(dir string, o Options) (Plan, error) {
	var pkg packageJSON
	b, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		return Plan{}, err
	}
	if err := json.Unmarshal(b, &pkg); err != nil {
		return Plan{}, fmt.Errorf("package.json: %w", err)
	}
	a := &nodeApp{dir: dir, pkg: pkg, pm: detectPackageManager(dir), o: o, image: nodeImage(o.NodeVersion)}

	fw := o.Framework
	if fw == "" {
		fw = a.detectFramework()
	}
	switch fw {
	case FrameworkNext:
		return a.next()
	case FrameworkNuxt:
		return a.nuxt()
	case FrameworkSvelteKit:
		return a.svelteKit()
	case FrameworkRemix:
		return a.remix()
	case FrameworkReactRouter:
		return a.reactRouter()
	case FrameworkAstro:
		return a.astro()
	case FrameworkNestJS:
		return a.nest()
	case FrameworkVite:
		return a.spa("Vite", "node_modules/.bin/vite build", "dist", "vite")
	case FrameworkCreateReactApp:
		return a.spa("Create React App", "node_modules/.bin/react-scripts build", "build", "react-scripts")
	case FrameworkExpress:
		return a.generic("Express")
	}
	return a.generic("Node.js")
}

// detectFramework picks a preset from the dependencies. Meta-frameworks come
// before Vite, which most of them build with.
func (a *nodeApp) detectFramework() string {
	switch {
	case a.has("next"):
		return FrameworkNext
	case a.has("nuxt"), a.has("nuxt3"):
		return FrameworkNuxt
	case a.has("@sveltejs/kit"):
		return FrameworkSvelteKit
	case a.has("@remix-run/dev"), a.has("@remix-run/serve"), a.has("@remix-run/node"):
		return FrameworkRemix
	case a.has("@react-router/dev"):
		return FrameworkReactRouter
	case a.has("astro"):
		return FrameworkAstro
	case a.has("@nestjs/core"):
		return FrameworkNestJS
	case a.has("vite"):
		return FrameworkVite
	case a.has("react-scripts"):
		return FrameworkCreateReactApp
	case a.has("express"):
		return FrameworkExpress
	}
	return ""
}

func (a *nodeApp) has(dep string) bool {
	if _, ok := a.pkg.Dependencies[dep]; ok {
		return true
	}
	_, ok := a.pkg.DevDependencies[dep]
	return ok
}

// buildCommand is the build command setting, else the "build" script, else
// fallback (which may be "": no build step).
func (a *nodeApp) buildCommand(fallback string) string {
	switch {
	case a.o.BuildCommand != "":
		return a.o.BuildCommand
	case a.pkg.Scripts["build"] != "":
		return a.pm.run + " build"
	}
	return fallback
}

// buildStage writes the build stage up to the copied source:
// manifests first, so the install layer is cached until dependencies change.
func (a *nodeApp) buildStage(title string) *strings.Builder {
	df := &strings.Builder{}
	fmt.Fprintf(df, "# generated by paas: %s (%s)\n", title, a.pm.name)
	fmt.Fprintf(df, "FROM %s AS build\nWORKDIR /app\n", a.image)
	if a.pm.setup != "" {
		fmt.Fprintf(df, "RUN %s\n", a.pm.setup)
	}
	if a.o.InstallCommand != "" {
		// A custom install step may need any file of the project.
		df.WriteString("COPY . .\n")
		fmt.Fprintf(df, "RUN --mount=type=cache,target=%s %s\n", a.pm.cache, a.o.InstallCommand)
		return df
	}
	manifests := "package.json"
	if a.pm.lockfile != "" {
		manifests += " " + a.pm.lockfile
	}
	fmt.Fprintf(df, "COPY %s ./\n", manifests)
	fmt.Fprintf(df, "RUN --mount=type=cache,target=%s %s\n", a.pm.cache, a.pm.install)
	df.WriteString("COPY . .\n")
	return df
}

// runEnv is written before CMD in every node server image.
func runEnv(df *strings.Builder, extra string) {
	fmt.Fprintf(df, "ENV NODE_ENV=production PORT=%d%s\nEXPOSE %d\nUSER %s\n", Port, extra, Port, appUser)
}

// server finishes a single-stage image that runs cmd (a CMD line) in the
// build stage with all of /app.
func (a *nodeApp) server(df *strings.Builder, name, build, cmd, how string) Plan {
	if build != "" {
		fmt.Fprintf(df, "RUN %s\n", build)
	}
	runEnv(df, " HOST=0.0.0.0")
	df.WriteString(cmd)
	return Plan{Kind: KindNode, Framework: name, Summary: fmt.Sprintf("%s server (%s, %s)", name, a.pm.name, how),
		Dockerfile: df.String()}
}

// customStart runs the start command setting (or Procfile web process) in
// place of a preset's own server; ok is false when there is none.
func (a *nodeApp) customStart(name, build string) (Plan, bool) {
	start, how := startCommand(a.dir, a.o)
	if start == "" {
		return Plan{}, false
	}
	return a.server(a.buildStage(name), name, build, shellCmd(start), how), true
}

// static builds and serves out (or the output directory setting) with nginx.
func (a *nodeApp) static(name, build, out string) (Plan, error) {
	if build == "" {
		return Plan{}, fmt.Errorf("%s needs a build step: add a \"build\" script or set the build command", name)
	}
	if a.o.OutputDirectory != "" {
		out = a.o.OutputDirectory
	}
	df := a.buildStage(name)
	fmt.Fprintf(df, `RUN %s && \
    if [ ! -d %q ]; then echo "the build produced no %s/ directory; set the output directory" >&2; exit 1; fi
FROM %s
COPY --from=build /app/%s/ /usr/share/nginx/html/
EXPOSE %d
`, build, out, out, nginxImage, out, Port)
	return Plan{Kind: KindNode, Framework: name, Summary: fmt.Sprintf("%s static build (%s, %s/)", name, a.pm.name, out),
		Dockerfile: df.String()}, nil
}

// ---- presets ----

var (
	nextOutput  = regexp.MustCompile(`output\s*:\s*['"](standalone|export)['"]`)
	ssrDisabled = regexp.MustCompile(`ssr\s*:\s*false`)
)

// configMatch returns the first submatch of re in any of the config files.
func (a *nodeApp) configMatch(re *regexp.Regexp, files ...string) string {
	for _, f := range files {
		b, err := os.ReadFile(filepath.Join(a.dir, f))
		if err != nil {
			continue
		}
		if m := re.FindSubmatch(b); m != nil {
			if len(m) > 1 {
				return string(m[1])
			}
			return string(m[0])
		}
	}
	return ""
}

func configFiles(base string) []string {
	return []string{base + ".js", base + ".mjs", base + ".ts", base + ".cjs", base + ".mts"}
}

// next: `next build`; output: 'standalone' runs the traced server alone,
// output: 'export' is a static site in out/, otherwise `next start`.
func (a *nodeApp) next() (Plan, error) {
	const name = "Next.js"
	build := a.buildCommand("node_modules/.bin/next build")
	output := a.configMatch(nextOutput, configFiles("next.config")...)
	if output == "export" || (a.o.OutputDirectory != "" && a.o.StartCommand == "") {
		return a.static(name, build, "out")
	}
	// The build cache survives between builds; the runtime may write to it.
	cachedBuild := "--mount=type=cache,target=/app/.next/cache " + build
	if p, ok := a.customStart(name, cachedBuild); ok {
		return p, nil
	}
	df := a.buildStage(name)
	df.WriteString("ENV NEXT_TELEMETRY_DISABLED=1\n")
	if output != "standalone" {
		fmt.Fprintf(df, "RUN %s\nRUN mkdir -p .next/cache && chown -R %s .next/cache\n", cachedBuild, appUser)
		runEnv(df, " NEXT_TELEMETRY_DISABLED=1")
		df.WriteString(shellCmd("exec node_modules/.bin/next start -H 0.0.0.0 -p $PORT"))
		return Plan{Kind: KindNode, Framework: name, Summary: fmt.Sprintf("%s server (%s, next start)", name, a.pm.name),
			Dockerfile: df.String()}, nil
	}
	fmt.Fprintf(df, "RUN %s\n", cachedBuild)
	fmt.Fprintf(df, "FROM %s\nWORKDIR /app\n", a.image)
	if exists(a.dir, "public") {
		fmt.Fprintf(df, "COPY --from=build --chown=%s /app/public ./public\n", appUser)
	}
	fmt.Fprintf(df, "COPY --from=build --chown=%s /app/.next/standalone ./\n", appUser)
	fmt.Fprintf(df, "COPY --from=build --chown=%s /app/.next/static ./.next/static\n", appUser)
	runEnv(df, " NEXT_TELEMETRY_DISABLED=1")
	// Kubernetes sets HOSTNAME to the pod name; the server binds to it.
	df.WriteString(shellCmd("HOSTNAME=0.0.0.0 exec node server.js"))
	return Plan{Kind: KindNode, Framework: name, Summary: fmt.Sprintf("%s standalone server (%s)", name, a.pm.name),
		Dockerfile: df.String()}, nil
}

// nuxt: `nuxt generate` is static (.output/public); `nuxt build` is a
// self-contained server in .output/.
func (a *nodeApp) nuxt() (Plan, error) {
	const name = "Nuxt"
	build := a.buildCommand("node_modules/.bin/nuxt build")
	if strings.Contains(build, "generate") || strings.Contains(a.pkg.Scripts["build"], "nuxt generate") ||
		(a.o.OutputDirectory != "" && a.o.StartCommand == "") {
		return a.static(name, build, ".output/public")
	}
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	df := a.buildStage(name)
	fmt.Fprintf(df, "RUN %s\n", build)
	fmt.Fprintf(df, "FROM %s\nWORKDIR /app\nCOPY --from=build /app/.output ./.output\n", a.image)
	runEnv(df, " HOST=0.0.0.0")
	fmt.Fprintf(df, "CMD [%q, %q]\n", "node", ".output/server/index.mjs")
	return Plan{Kind: KindNode, Framework: name, Summary: fmt.Sprintf("%s server (%s, .output/server/index.mjs)", name, a.pm.name),
		Dockerfile: df.String()}, nil
}

var svelteAdapter = regexp.MustCompile(`@sveltejs/adapter-(node|static|auto)`)

// svelteKit: adapter-node runs build/index.js, adapter-static serves build/.
func (a *nodeApp) svelteKit() (Plan, error) {
	const name = "SvelteKit"
	build := a.buildCommand("node_modules/.bin/vite build")
	adapter := ""
	switch {
	case a.has("@sveltejs/adapter-node"):
		adapter = "node"
	case a.has("@sveltejs/adapter-static"):
		adapter = "static"
	default:
		adapter = a.configMatch(svelteAdapter, configFiles("svelte.config")...)
	}
	if adapter == "static" || (a.o.OutputDirectory != "" && a.o.StartCommand == "") {
		return a.static(name, build, "build")
	}
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	if adapter != "node" {
		return Plan{}, errors.New("SvelteKit needs @sveltejs/adapter-node (server) or @sveltejs/adapter-static " +
			"(static site) on this platform; adapter-auto does not produce a runnable build")
	}
	return a.server(a.buildStage(name), name, build, fmt.Sprintf("CMD [%q, %q]\n", "node", "build/index.js"),
		"node build/index.js"), nil
}

// remix runs the "start" script, else remix-serve on the server build.
func (a *nodeApp) remix() (Plan, error) {
	const name = "Remix"
	build := a.buildCommand("node_modules/.bin/remix build")
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	df := a.buildStage(name)
	if a.pkg.Scripts["start"] != "" {
		return a.server(df, name, build, fmt.Sprintf("CMD [%q, %q]\n", "npm", "start"), `"start" script`), nil
	}
	if !a.has("@remix-run/serve") {
		return Plan{}, errors.New(`Remix app has no "start" script and no @remix-run/serve; add one or set the start command`)
	}
	entry := "build/index.js"
	if exists(a.dir, "vite.config.ts") || exists(a.dir, "vite.config.js") || exists(a.dir, "vite.config.mjs") {
		entry = "build/server/index.js"
	}
	return a.server(df, name, build, fmt.Sprintf("CMD [%q, %q]\n", "node_modules/.bin/remix-serve", entry),
		"remix-serve "+entry), nil
}

// reactRouter (v7 framework mode): ssr: false is a static build/client,
// otherwise react-router-serve.
func (a *nodeApp) reactRouter() (Plan, error) {
	const name = "React Router"
	build := a.buildCommand("node_modules/.bin/react-router build")
	if a.configMatch(ssrDisabled, configFiles("react-router.config")...) != "" ||
		(a.o.OutputDirectory != "" && a.o.StartCommand == "") {
		return a.static(name, build, "build/client")
	}
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	df := a.buildStage(name)
	if a.pkg.Scripts["start"] != "" {
		return a.server(df, name, build, fmt.Sprintf("CMD [%q, %q]\n", "npm", "start"), `"start" script`), nil
	}
	if !a.has("@react-router/serve") {
		return Plan{}, errors.New(`React Router app has no "start" script and no @react-router/serve; add one or set the start command`)
	}
	return a.server(df, name, build,
		fmt.Sprintf("CMD [%q, %q]\n", "node_modules/.bin/react-router-serve", "build/server/index.js"),
		"react-router-serve build/server/index.js"), nil
}

// astro: with the node adapter a standalone server, otherwise static dist/.
func (a *nodeApp) astro() (Plan, error) {
	const name = "Astro"
	build := a.buildCommand("node_modules/.bin/astro build")
	if !a.has("@astrojs/node") && a.o.StartCommand == "" {
		return a.static(name, build, "dist")
	}
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	return a.server(a.buildStage(name), name, build, fmt.Sprintf("CMD [%q, %q]\n", "node", "dist/server/entry.mjs"),
		"node dist/server/entry.mjs"), nil
}

// nest: `nest build`, then "start:prod" or node dist/main.
func (a *nodeApp) nest() (Plan, error) {
	const name = "NestJS"
	build := a.buildCommand("node_modules/.bin/nest build")
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	df := a.buildStage(name)
	if a.pkg.Scripts["start:prod"] != "" {
		return a.server(df, name, build, fmt.Sprintf("CMD [%q, %q, %q]\n", "npm", "run", "start:prod"),
			`"start:prod" script`), nil
	}
	return a.server(df, name, build, fmt.Sprintf("CMD [%q, %q]\n", "node", "dist/main"), "node dist/main"), nil
}

// spa (Vite, Create React App) is a static build, unless a start command,
// a Procfile or a "start" script that is not the dev server says otherwise.
func (a *nodeApp) spa(name, fallbackBuild, out, devServer string) (Plan, error) {
	build := a.buildCommand(fallbackBuild)
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	if s := a.pkg.Scripts["start"]; s != "" && !strings.HasPrefix(s, devServer) && a.o.OutputDirectory == "" {
		return a.server(a.buildStage(name), name, a.buildCommand(""),
			fmt.Sprintf("CMD [%q, %q]\n", "npm", "start"), `"start" script`), nil
	}
	return a.static(name, build, out)
}

// generic is any other Node project (and Express): start command or
// Procfile, "start" script, a static build, or server.js/index.js.
func (a *nodeApp) generic(name string) (Plan, error) {
	build := a.buildCommand("")
	if p, ok := a.customStart(name, build); ok {
		return p, nil
	}
	switch {
	case a.pkg.Scripts["start"] != "":
		// A server: build (if there is a build step) and run "start".
		return a.server(a.buildStage(name), name, build, fmt.Sprintf("CMD [%q, %q]\n", "npm", "start"),
			`"start" script`), nil
	case a.o.OutputDirectory != "":
		return a.static(name, build, a.o.OutputDirectory)
	case build != "":
		// No server, but a build step: a single-page app or static site
		// generator. Serve whichever output directory the build produced.
		df := a.buildStage(name)
		fmt.Fprintf(df, `RUN %s && \
    for d in dist build out public; do \
      if [ -f "$d/index.html" ]; then cp -r "$d" /site && exit 0; fi; \
    done; \
    echo "build produced no dist/, build/, out/ or public/ directory with index.html; set the output directory" >&2; exit 1
FROM %s
COPY --from=build /site/ /usr/share/nginx/html/
EXPOSE %d
`, build, nginxImage, Port)
		return Plan{Kind: KindNode, Framework: name, Summary: fmt.Sprintf("%s static build (%s, %q)", name, a.pm.name, build),
			Dockerfile: df.String()}, nil
	}

	entry := a.pkg.Main
	if entry == "" {
		for _, f := range []string{"server.js", "index.js", "app.js"} {
			if exists(a.dir, f) {
				entry = f
				break
			}
		}
	}
	if entry == "" {
		return Plan{}, errors.New(`package.json has no "start" or "build" script and no server.js/index.js; ` +
			`add a "start" script or set the start command`)
	}
	return a.server(a.buildStage(name), name, "", fmt.Sprintf("CMD [%q, %q]\n", "node", entry), "node "+entry), nil
}
