package build

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const defaultRubyVersion = "3.3"

var (
	gemfileRuby = regexp.MustCompile(`(?m)^\s*ruby\s+['"](\d+\.\d+)`)
	rubyVersion = regexp.MustCompile(`(\d+\.\d+)`)
)

// detectRuby builds with the full ruby image (compilers and -dev headers for
// native gems) and runs on the slim one.
func detectRuby(dir string, o Options) (Plan, error) {
	version := defaultRubyVersion
	if b, err := os.ReadFile(filepath.Join(dir, "Gemfile")); err == nil {
		if m := gemfileRuby.FindSubmatch(b); m != nil {
			version = string(m[1])
		}
	}
	if version == defaultRubyVersion {
		if b, err := os.ReadFile(filepath.Join(dir, ".ruby-version")); err == nil {
			if m := rubyVersion.FindSubmatch(b); m != nil {
				version = string(m[1])
			}
		}
	}

	manifests := "Gemfile"
	gems, _ := os.ReadFile(filepath.Join(dir, "Gemfile"))
	if lock, err := os.ReadFile(filepath.Join(dir, "Gemfile.lock")); err == nil {
		manifests += " Gemfile.lock"
		gems = lock
	}
	hasGem := func(name string) bool {
		return regexp.MustCompile(`(?m)^\s*(gem\s+['"])?` + regexp.QuoteMeta(name) + `(\s|['"]|$)`).Match(gems)
	}

	rails := exists(dir, "config.ru") && exists(dir, "bin", "rails")
	name := "Ruby"
	switch {
	case rails:
		name = "Rails"
	case exists(dir, "config.ru"):
		name = "Rack"
	}
	// The start command setting or the Procfile, else the server we know.
	command, how := startCommand(dir, o)
	switch {
	case command != "":
	case rails:
		command = "exec bundle exec rails server -b 0.0.0.0 -p $PORT"
		how = "Rails: rails server"
	case exists(dir, "config.ru") && hasGem("puma"):
		command = "exec bundle exec puma -b tcp://0.0.0.0:$PORT"
		how = "Rack: puma"
	case exists(dir, "config.ru") && hasGem("rackup"):
		command = "exec bundle exec rackup -o 0.0.0.0 -p $PORT"
		how = "Rack: rackup"
	case exists(dir, "config.ru"):
		return Plan{}, errors.New("config.ru found but neither puma nor rackup is in the Gemfile; add puma")
	default:
		return Plan{}, errors.New("Gemfile found but no config.ru or Procfile web process; " +
			"add a Procfile with a \"web:\" line or set the start command")
	}

	var df strings.Builder
	fmt.Fprintf(&df, "# generated by paas: ruby %s (%s)\n", version, how)
	fmt.Fprintf(&df, "FROM ruby:%s AS build\n", version)
	df.WriteString("ENV BUNDLE_WITHOUT=development:test BUNDLE_GLOBAL_GEM_CACHE=true\nWORKDIR /app\n")
	if o.InstallCommand != "" {
		// A custom install step may need any file of the project.
		df.WriteString("COPY . .\n")
		fmt.Fprintf(&df, "RUN --mount=type=cache,target=/root/.bundle/cache %s\n", o.InstallCommand)
	} else {
		// Manifests first, so the bundle layer is cached until dependencies change.
		fmt.Fprintf(&df, "COPY %s ./\n", manifests)
		df.WriteString("RUN --mount=type=cache,target=/root/.bundle/cache bundle install --jobs 4\n")
		df.WriteString("COPY . .\n")
	}
	env := fmt.Sprintf("RACK_ENV=production PORT=%d", Port)
	if rails {
		env += " RAILS_ENV=production RAILS_LOG_TO_STDOUT=1 RAILS_SERVE_STATIC_FILES=1"
		if exists(dir, "app", "assets") && o.BuildCommand == "" {
			df.WriteString("RUN SECRET_KEY_BASE_DUMMY=1 RAILS_ENV=production bundle exec rails assets:precompile\n")
		}
	}
	if o.BuildCommand != "" {
		fmt.Fprintf(&df, "RUN %s\n", o.BuildCommand)
		how += ", build command: " + o.BuildCommand
	}
	// Rails writes pids and caches under tmp/; nothing else is writable.
	df.WriteString("RUN mkdir -p tmp log && chown -R " + appUser + " tmp log\n")

	fmt.Fprintf(&df, "FROM ruby:%s-slim\n", version)
	if hasGem("pg") {
		df.WriteString("RUN apt-get update && apt-get install -y --no-install-recommends libpq5 && rm -rf /var/lib/apt/lists/*\n")
	}
	fmt.Fprintf(&df, "ENV BUNDLE_WITHOUT=development:test HOME=/tmp %s\n", env)
	df.WriteString("COPY --from=build /usr/local/bundle /usr/local/bundle\n")
	df.WriteString("WORKDIR /app\nCOPY --from=build /app /app\n")
	fmt.Fprintf(&df, "EXPOSE %d\nUSER %s\n", Port, appUser)
	df.WriteString(shellCmd(command))
	return Plan{Kind: KindRuby, Framework: name, Summary: fmt.Sprintf("ruby %s (%s)", version, how), Dockerfile: df.String()}, nil
}
